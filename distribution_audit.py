"""Release checks: reviewed file allowlist, content hashes and clean state.

The allowlist is checked in, never regenerated by build.py. Changes to any
source, voice sample or artwork must be reviewed before updating its hash.
Unicode escapes below distinguish exclusion rules from actual payload text.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

RULES = re.compile(r'\u80a0\u4ed4|\u6d77\u8c79|suited[._-]seal|seal[-_]renderer|chang[z]ai', re.I)
PRIVATE = re.compile(r'192\.168\.50\.(?:10|13)|aixiao[m]aibu|(?<![A-Za-z0-9_-])sk-(?:[A-Za-z0-9]{32,}|proj-[A-Za-z0-9_-]{32,})(?![A-Za-z0-9_-])', re.I)
_labels = ('\u80a0\u4ed4', '\u6d77\u8c79', 'chang' + 'zai',
           *('suited' + s + 'seal' for s in '._-'),
           *('seal' + s + 'renderer' for s in '-_'))
_unicode_signatures = tuple(s.encode(e) for s in _labels if not s.isascii()
                            for e in ('utf-8', 'utf-16-le', 'utf-16-be'))
_ascii_signatures = tuple(s.encode(e) for s in _labels if s.isascii()
                          for e in ('utf-8', 'utf-16-le', 'utf-16-be'))
_private_bytes = re.compile(PRIVATE.pattern.encode('ascii'), re.I)


def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def ignored(path):
    return any(p in ('__pycache__', '.DS_Store') or p.startswith('._') for p in path.parts) or path.suffix == '.pyc'


def checked_files(root):
    files = {}
    for directory in ('source', 'assets'):
        for path in (root / directory).rglob('*'):
            if ignored(path.relative_to(root)):
                continue
            if path.is_symlink():
                raise ValueError(f'Symbolic link is not a release input: {path}')
            if path.is_file():
                files[path.relative_to(root).as_posix()] = path
    return files


def validate_inputs(root):
    lock = json.loads((root / 'distribution-files.json').read_text(encoding='utf-8'))
    files = checked_files(root)
    expected = lock['files']
    if set(files) != set(expected):
        raise ValueError(f'Release inputs changed: extra={sorted(set(files) - set(expected))}; '
                         f'missing={sorted(set(expected) - set(files))}')
    for name, path in files.items():
        if path.stat().st_size != expected[name]['size'] or digest(path) != expected[name]['sha256']:
            raise ValueError(f'Release input hash changed: {name}')
    return {'locked_source_and_asset_files': len(files), 'input_hashes_verified': True}


def scan_files(root):
    """Scan filenames and UTF-8 / UTF-16 contents, without printing secrets."""
    count, hits = 0, []
    for path in root.rglob('*'):
        relative = path.relative_to(root).as_posix()
        if path.is_symlink():
            raise ValueError(f'Symbolic link in release: {relative}')
        if RULES.search(relative):
            hits.append(relative)
        if not path.is_file():
            continue
        count += 1
        # Read in blocks with overlap so boundary-spanning text is checked.
        tail = b''
        with path.open('rb') as stream:
            for block in iter(lambda: stream.read(1024 * 1024), b''):
                data = tail + block
                lower = data.lower()
                # Literal bytes cover UTF-16 even at odd offsets in binaries.
                matched = (any(signature in data for signature in _unicode_signatures)
                           or any(signature in lower for signature in _ascii_signatures))
                if not matched and any(prefix in lower for prefix in (b'192.', b'aixiao', b'sk-')):
                    matched = bool(_private_bytes.search(data))
                if matched:
                    hits.append(relative)
                    break
                tail = data[-1024:]
    if hits:
        raise ValueError('Excluded data detected in: ' + ', '.join(sorted(set(hits))))
    return {'files_scanned': count, 'excluded_data_matches': 0}


def validate_payload(app, root):
    payload = app / 'resources/app/payload'
    expected = set()
    lock = json.loads((root / 'distribution-files.json').read_text(encoding='utf-8'))['files']
    for name, record in lock.items():
        if name.startswith('source/') and name != 'source/hojo-80m/zh1.wav':
            name = name.removeprefix('source/')
            expected.add(name)
            if digest(payload / name) != record['sha256']:
                raise ValueError(f'Source copy mismatch: {name}')
    model_count = 0
    for mode in ('40m', '80m'):
        manifest = json.loads((payload / f'hojo-{mode}/model-manifest.json').read_text())
        for name, record in manifest['files'].items():
            rel = f'hojo-{mode}/models/{name}'; expected.add(rel)
            if digest(payload / rel) != record['sha256']:
                raise ValueError(f'Official model hash mismatch: {rel}')
            model_count += 1
            if mode == '80m':
                rel = f'hojo-{mode}/optimized/int8-v1/{name}'; expected.add(rel)
                sha = 'e96ec82e538841bec82d3c545b3fcee3c6c2b9a4ca1ac45f3465015640ffd14c' if name == 'Hojo-TTS-Light-llm.onnx' else record['sha256']
                if digest(payload / rel) != sha:
                    raise ValueError(f'Optimized model hash mismatch: {rel}')
    expected.update(('hojo-80m/optimized/int8-v1/optimization.json', 'character-default.json',
                     'build-provenance.json', 'bin/douyinLive.exe', 'bin/ffmpeg.exe'))
    voice = 'voices/hojo80_demo_zh_f_01/'
    expected.update((voice + 'reference.wav', voice + 'voice.json'))
    sample_hash = lock['source/hojo-80m/zh1.wav']['sha256']
    if digest(payload / (voice + 'reference.wav')) != sample_hash:
        raise ValueError('Official voice reference does not match reviewed sample')
    for name in ('LICENSE', 'README.md', 'config.example.yaml', 'docs/http-api.md', 'sign/README.md'):
        expected.add('licenses/douyinLive/' + name)
    for name in ('LICENSE', 'LICENSE.txt', 'NOTICE.txt', 'COPYING', 'README.md', 'SOURCE.txt'):
        # Actual upstream wheel filenames vary. Only shipped license texts allowed.
        if (payload / 'licenses/ffmpeg' / name).is_file():
            expected.add('licenses/ffmpeg/' + name)
    actual = {p.relative_to(payload).as_posix() for p in payload.rglob('*') if p.is_file()}
    if actual != expected:
        raise ValueError(f'Payload file set mismatch: extra={sorted(actual - expected)}; missing={sorted(expected - actual)}')
    profile = json.loads((payload / 'character-default.json').read_text())
    if profile['name'] != '小雅' or profile['voice_template'] != 'hojo_zh_f_02':
        raise ValueError('Fresh profile differs from distribution defaults')
    return {'payload_files_verified': len(actual), 'official_model_files_verified': model_count,
            'reference_voice_files': 1, 'user_state_files': 0, 'unexpected_payload_files': 0,
            'default_character': 'whale_girl_v1', 'default_voice': profile['voice_template']}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--app', type=Path, required=True)
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    report = {**validate_inputs(root), **validate_payload(args.app, root), **scan_files(args.app)}
    output = json.dumps(report, ensure_ascii=False, indent=2)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(output, encoding='utf-8')
    print(output)
